@dataclass(frozen=True)
class PlacementBinding:
    """How a PLACED component in this tool's design files carries the id of the Stockroom
    library part it is bound to.

    A binding is what makes an assignment durable: a designator is renumbered by annotation
    and a Value is edited freely, so neither can key the link. `field` is the placement field
    that holds the part id; `writable` says whether Stockroom can put it there itself.

    `writable=False` is not a missing feature, it is a fact about the tool, and it decides
    where the binding is STORED: a tool Stockroom can write carries its binding inside the
    design (atomic with the same byte-preserving write, and it travels with the file), while
    a tool Stockroom can only read keeps it on the Stockroom project record instead.
    """

    field: str = "Stockroom ID"
    writable: bool = False
    # Why the design cannot be written, shown to the user rather than left as silence.
    reason: str = ""


@dataclass(frozen=True)
class EmbeddedAsset:
    """An asset kind this tool can only receive by having the TOOL ITSELF write it into a
    binary container the part already owns.

    This is a different fact from `unsupported_assets`, and conflating them is what kept
    Altium 3D permanently out of reach. Both are true of an Altium 3D model at once:

    - it cannot be given BY REFERENCE (no database column or path carries a 3D body), which is
      what `unsupported_assets` records, and it is why a capture session must never be asked to
      fetch one;
    - it CAN be obtained, by driving the tool to embed the model file the part already holds,
      which is what this records, and it is why the gap is worth reporting.

    So a kind listed here is a CLOSABLE gap. That distinction matters: reporting a gap that can
    never be closed is exactly what "CAD Incomplete forever" looked like, while hiding a gap that
    CAN be closed is how Altium parts silently shipped with no 3D at all.
    """

    # The asset whose file receives the payload (an Altium 3D body lives in the footprint's
    # `.PcbLib`), and the asset kind that SUPPLIES the payload. The source is normally the same
    # kind held for another tool: one STEP file serves every tool, so nothing is captured twice.
    container: str = "footprint"
    source: str = "model"
    # Embedding runs the real EDA tool, so it needs that tool installed on THIS machine. Stated
    # as data because a KiCad-only peer must be told why the action is unavailable rather than
    # watching it silently do nothing.
    requires_tool_installed: bool = True
    reason: str = ""


@dataclass(frozen=True)
class PathContract:
    """How this tool makes a library reference resolve to the same asset on every machine.

    A project stores references to library symbols, footprints and 3D models, and a library lives
    at a different absolute path on every peer's disk. Whether a stored reference survives that is
    a fact about the TOOL, not about any one surface, so it belongs here: KiCad resolves through a
    path VARIABLE it holds in its own config, while Altium's .DbLib carries an absolute data-source
    path and so is rebuilt on each machine instead of travelling.

    Generic code (the library-version pin surface, the doctor, onboarding) reads this instead of
    knowing that `SR_LIB` is a KiCad concept.
    """

    # "env_var": the tool resolves through a named variable that must be set on each machine.
    # "relative": references are relative to the library folder, so nothing has to be set.
    # "derived": the file carrying the references is machine-specific, so Stockroom REGENERATES it
    #   locally. Nothing to set, but the rebuild is not optional. Do not conflate this with
    #   "relative": that one promises the artifact travels as it stands, which for a .DbLib is the
    #   exact belief that shipped a library nobody could connect to (see _ALTIUM.path_contract).
    kind: str = "relative"
    # The variable's name, and the tool config file Stockroom writes it into, for an honest
    # message when it is missing. Empty for a relative contract.
    variable: str = ""
    config_file: str = ""
    # What a portable reference literally starts with, so a surface can SHOW the shape.
    prefix: str = ""
    description: str = ""


@dataclass(frozen=True)
class DataField:
    """One piece of RECORD data a tool receives when a part is placed from the library.

    This is the answer to "what does an EDA tool actually get from this part", and it is the
    registry's job because the answer differs per tool: KiCad takes five schematic properties, while
    an Altium DbLib row carries commercial columns (price, stock, lifecycle) that KiCad has no
    property for. Before this existed the same question was answered independently by
    `altium/dblib.FIELD_MAP`, `altium/datasource.ALTIUM_COLUMNS` and `projects/fill.COMPLETION_FIELDS`,
    so a column added in one place was silently missing from the others.

    ASSET references are deliberately in scope (`footprint` for KiCad): a schematic property holding
    a footprint ref is data the tool receives exactly like an MPN is, and the surface that reports
    the handoff must not draw an arbitrary line through it.
    """

    # The record-derived value this carries. Lower-case, stable, and the key generic code and the
    # frontend both join on - never the tool's own spelling, which differs between tools.
    key: str
    # What a PERSON calls it. Shared across tools so one field is one row in the union.
    label: str
    # What THIS tool calls it: a `.kicad_sch` property name, or an Altium Design Parameter. Altium's
    # bracket syntax is meaningful (a bracketed name is a reserved model/attribute binding, a bare
    # one is an ordinary parameter), so it is carried verbatim rather than derived from the label.
    tool_field: str
    # Whether the tool shows this on the placed component by default (Altium's VisibleOnAdd).
    visible: bool = False
    # Whether a PLACED component can be measured as missing this. Nearly always true.
    #
    # False is for a field the tool receives structurally rather than as a fillable property: a
    # KiCad component's symbol arrives as its `lib_id`, and a component cannot exist without one,
    # so "components missing a symbol" is not a countable thing and a completion passport that
    # counted it would report a gap no action could ever close. The field is still declared,
    # because the handoff band must say the symbol reaches KiCad - leaving it out was the
    # alternative, and it made the surface claim symbols go to Altium alone.
    passport: bool = True


# WHO OWNS a field's value. Declared ONCE, globally, rather than per tool: "a price comes from a
# vendor" is a fact about the field itself and is equally true for every tool that carries it, so a
# per-tool flag would be the same answer written twice with a chance to disagree.
#
# Three origins, because there really are three and collapsing them misleads:
#
#   "curated" - a PERSON maintains it. These are the fields the detail sheet's handoff band shows
#       and offers to edit, because they are the ones somebody is responsible for getting right.
#   "vendor"  - a DISTRIBUTOR supplies it and a Refresh overwrites it. Already the Sourcing
#       column's whole subject, with a vendor attribution and a refresh control there, and it
#       changes on its own between sessions. Repeating it at the top of the sheet would be both
#       duplication and a lie about who owns the value.
#   "derived" - COMPUTED from other record fields when the artifact is emitted, and never stored.
#       An Altium `Value` column is a passive's parametric value or an active's MPN, worked out at
#       emit time by `ingest.component_naming.derive_value`. There is no stored value to show and
#       nothing to edit, and re-deriving it in the frontend to fill a cell would fork that rule
#       into a second implementation that drifts - which is exactly what this registry exists to
#       prevent. So the band omits it rather than guessing.
#
# A field absent from this map is "curated", which is the safe default: it appears, and somebody
# notices it should not, rather than silently vanishing from the surface.
FIELD_ORIGINS: dict[str, str] = {
    "supplier": "vendor",
    "supplier_part_number": "vendor",
    "supplier_url": "vendor",
    "price": "vendor",
    "stock": "vendor",
    "lifecycle": "vendor",
    "value": "derived",
}


@dataclass(frozen=True)
class UnionField:
    """One row of `data_field_union`: a field, and every tool that consumes it."""

    key: str
    label: str
    # Registry declaration order, so a surface can say "KiCad and Altium" in a stable order.
    tools: tuple[str, ...]
    # Who owns this value: "curated" | "vendor" | "derived". See FIELD_ORIGINS for what each
    # means and why it is one global declaration rather than a per-tool flag.
    origin: str = "curated"


@dataclass(frozen=True)
class EdaTool:
    """Everything generic code needs to know about one EDA tool.

    A capability a tool LACKS is data here, never an `if tool == "altium"` branch buried in
    shared logic.
    """

    key: str
    label: str
    # Stable machine-readiness checks and the Settings anchor that owns their repair. Primary EDA
    # policy reads these instead of branching on tool keys. A future tool declares its own setup
    # contract here and immediately participates in onboarding and Settings DTOs.
    setup_checks: tuple[str, ...] = ()
    settings_target: str = ""
    # Per-user or machine-generated files. Committing these is what makes two peers
    # conflict on every pull, so they are ignored in any synced workspace.
    ignore: tuple[str, ...] = ()
    # Formats that must never be text-normalized and must never be auto-merged. In git,
    # `binary` is shorthand for `-diff -merge -text`, so marking them also turns an
    # unmergeable-format collision into a LOUD conflict instead of a corrupted file.
    binary: tuple[str, ...] = ()
    # Formats that ARE text and must not be misdetected as binary (they diff and merge
    # normally, and we want that).
    text: tuple[str, ...] = ()
    # Patterns whose CONTENT belongs in git-lfs rather than in the git object database. Every
    # captured part otherwise adds a permanent, un-GC-able copy to history for every future cloner,
    # so a growing binary library makes every clone slower forever. Must be a SUBSET of `binary`:
    # a text format sent to LFS would stop diffing, which is the opposite of what it is for.
    lfs: tuple[str, ...] = ()
    # The subset of `lfs` that also gets git-lfs's check-out semantics (`lockable`): the file is
    # checked out READ-ONLY and only becomes writable to whoever holds the lock, which is the real
    # answer to "two people, never any errors" on a format nothing can merge.
    #
    # MEASURED 2026-07-25, and it decides what may appear here: a lockable file really is
    # `-r--r--r--` on disk, and `git lfs lock` FAILS outright (`missing protocol: ""`) on a repo
    # with no remote. So only files STOCKROOM ITSELF NEVER WRITES may be listed, or the app would
    # break its own operations (the Altium 3D embed writes into the .PcbLib), and emitting it at
    # all is gated on a live probe rather than assumed.
    lockable: tuple[str, ...] = ()
    # Files STOCKROOM ITSELF generates from the library records for this tool, and can regenerate
    # at any time. Kept apart from `ignore` because the two are different facts with different
    # remedies: a per-user file is somebody's window state and is gone for good, while a derived
    # file is rebuilt on demand. Sharing a derived artifact through git is worse than useless when
    # it is BINARY: two peers who each add a different part produce two unmergeable files carrying
    # no information the records do not already hold, so every such conflict is pure noise on a
    # file that can be recreated in milliseconds.
    derived: tuple[str, ...] = ()
    # Asset kinds this tool consumes. Generic readiness/capture code iterates these rather
    # than hardcoding "symbol, footprint, model".
    asset_kinds: tuple[str, ...] = ("symbol", "footprint", "model")
    # Asset kinds the tool CANNOT be given through Stockroom's normal reference mechanism,
    # mapped to why. Generic code reads this instead of special-casing a tool.
    unsupported_assets: dict[str, str] = field(default_factory=dict)
    # Asset kinds the tool takes only by EMBEDDING (see EmbeddedAsset). A kind may appear here
    # AND in `unsupported_assets`: it cannot be referenced, but it can be embedded.
    embedded_assets: dict[str, EmbeddedAsset] = field(default_factory=dict)
    # Record data this tool receives on placement, in the order the tool's own artifact declares it
    # (see DataField). Generic code and the detail sheet's handoff band iterate this; the Altium
    # DbLib column map and KiCad's completion passport are both DERIVED from it.
    data_fields: tuple[DataField, ...] = ()
    # How a placed component carries the library part it is bound to (see PlacementBinding).
    placement_binding: PlacementBinding = PlacementBinding()
    # How this tool's stored library references stay portable across machines (see PathContract).
    path_contract: PathContract = PathContract()

    # WHICH FORMS OF A DATASHEET THIS TOOL CAN ACTUALLY OPEN, best first.
    #
    #   "file" - a datasheet PDF stored in the library, referenced so the tool resolves it on any
    #            machine. Only a tool with a path contract that survives the trip can offer this.
    #   "url"  - the vendor's link. Always resolvable, always a round trip to the internet.
    #
    # A fact about the TOOL, so it lives here rather than as two hand-written orders in two
    # modules - which is what it was, and they had drifted into opposites. KiCad resolves
    # `${SR_LIB}/datasheets/<file>` through a path variable it holds in its own config, so a local
    # file is BETTER there. A .DbLib link column carries a plain string with no such variable, so
    # Altium can use a URL and nothing else - and the old fallback put a bare "X.pdf" in that
    # column, a link that resolves to nothing while the row still said "Datasheet" beside it.
    #
    # A form this tool cannot use is simply ABSENT here, so generic code offers nothing rather
    # than something broken. Adding a third tool is a registry entry, never a branch.
    datasheet_sources: tuple[str, ...] = ("url",)

    def ignored_patterns(self) -> tuple[str, ...]:
        """Every pattern this tool contributes to a workspace `.gitignore`, per-user AND derived.

        Generic code must read THIS rather than `ignore`, or a derived file that is already
        committed stays committed forever while the generated rules claim it is ignored (an ignore
        rule has no effect on a tracked file, which is the whole reason hygiene untracks).
        """
        return tuple(self.ignore) + tuple(self.derived)

    def capturable_assets(self) -> tuple[str, ...]:
        """Kinds a CAPTURE session can fetch by reference, in registered order.

        An embeddable kind is excluded: the payload comes from a file the part already holds, so
        asking a vendor for a second, tool-specific copy would be busywork.
        """
        return tuple(k for k in self.asset_kinds if k not in self.unsupported_assets)

    def closable_assets(self) -> tuple[str, ...]:
        """Kinds a part can actually END UP holding, in registered order.

        This is what readiness reports on, and it is deliberately wider than
        `capturable_assets`: a kind that cannot be referenced but CAN be embedded is a real gap
        with a real action behind it, so hiding it would be dishonest.
        """
        return tuple(
            k
            for k in self.asset_kinds
            if k not in self.unsupported_assets or k in self.embedded_assets
        )


