"""The EDA tool registry: the ONE place a tool's facts live.

Owner directive (2026-07-24): "i dont want any major system to be overly specific to one
thing just that our app can handle whatever." KiCad and Altium really are different; that
difference belongs HERE, as data, so every other subsystem stays generic and adding a third
tool is adding a registry entry rather than editing ten call sites.

This module is deliberately dependency-free and Qt-free so anything may import it.

The first consumer is workspace hygiene -- the generated `.gitignore` / `.gitattributes` for
a synced workspace. That is not busywork: the measured cause of the owner's KiCad peer-sync
failures was that nothing ignored KiCad's PER-USER files (`.kicad_prl` holds one user's
window state, `fp-info-cache` is a regenerated machine cache). Committed, they mutate on
every open, so two peers conflict on every pull while the actual design sources merge
perfectly. KiCad's own documentation says not to commit them. Generating these files from
the registry means no human has to remember any of it, for any tool.
"""
from __future__ import annotations

from dataclasses import dataclass, field

