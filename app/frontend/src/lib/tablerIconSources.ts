const TRANSPARENT_FRAME = /\s*<path stroke="none" d="M0 0h24v24H0z" fill="none" \/>\s*/;

export function tablerBody(raw: string): string {
  const match = raw.match(/<svg\b[^>]*>([\s\S]*?)<\/svg>/i);
  if (!match) throw new Error("Tabler asset is missing its SVG root");
  return match[1].replace(TRANSPARENT_FRAME, "").trim();
}
